# TLS ACTIVE PROBE
# ============================================================

def tls_probe(
    ip,
    port,
    hostname
):

    if not ACTIVE_PROBES:
        return

    if not TLS_PROBE_ENABLED:
        return

    if port != 443:
        return

    if not safe_for_active_probe(
        ip
    ):
        return


    key = (
        ip,
        port,
        hostname
    )


    with probe_lock:

        if key in tls_probed:
            return

        if (
            len(tls_probed)
            >= MAX_TLS_PROBES
        ):
            return

        tls_probed.add(
            key
        )


    server_name = (
        hostname
        if hostname
        else ip
    )


    try:

        context = (
            ssl.create_default_context()
        )


        with socket.create_connection(
            (
                ip,
                port
            ),
            timeout=PROBE_TIMEOUT
        ) as raw:


            with context.wrap_socket(
                raw,
                server_hostname=server_name
            ) as tls_socket:


                certificate = (
                    tls_socket.getpeercert()
                )


                der = (
                    tls_socket.getpeercert(
                        binary_form=True
                    )
                )


        result = {

            "subject":
                certificate.get(
                    "subject"
                ),

            "issuer":
                certificate.get(
                    "issuer"
                ),

            "subjectAltName":
                certificate.get(
                    "subjectAltName"
                ),

            "serialNumber":
                certificate.get(
                    "serialNumber"
                ),

            "notBefore":
                certificate.get(
                    "notBefore"
                ),

            "notAfter":
                certificate.get(
                    "notAfter"
                )
        }


        if der:

            result[
                "sha256"
            ] = hashlib.sha256(
                der
            ).hexdigest()


        db_execute(
            """
            INSERT INTO probes
            (
                session_id,
                observed_at,
                probe_type,
                remote_ip,
                remote_port,
                hostname_candidate,
                result,
                source
            )
            VALUES
            (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                SESSION_ID,
                utc_now(),
                "TLS_CERTIFICATE",
                ip,
                port,
                hostname,
                json.dumps(
                    result,
                    default=str
                ),
                "ACTIVE_PROBE"
            )
        )


        print(
            "PROBE TLS   "
            f"{ip}:{port} "
            f"SNI={server_name}"
        )


    except Exception:

        pass


