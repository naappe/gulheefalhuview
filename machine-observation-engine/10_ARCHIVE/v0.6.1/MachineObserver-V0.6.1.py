def build_activity_report():

    with db_lock:

        rows = db.execute(
            """
            SELECT
                flow_id,
                pid,
                process,
                remote_ip,
                remote_port,
                forward_names,
                evidence_confidence

            FROM flows

            WHERE session_id=?

            ORDER BY first_seen
            """,
            (
                SESSION_ID,
            )
        ).fetchall()


    activities = defaultdict(
        lambda: {
            "flows": [],
            "processes": set(),
            "pids": set(),
            "hostnames": set(),
            "remote_ips": set(),
            "evidence": [],
            "classification": []
        }
    )


    for row in rows:

        names = []


        if row[
            "forward_names"
        ]:

            names = [

                item.strip()

                for item
                in row[
                    "forward_names"
                ].split("|")

                if item.strip()
            ]


        (
            category,
            meaning,
            class_score
        ) = classify_activity(
            row[
                "process"
            ],
            names,
            row[
                "remote_port"
            ]
        )


        key = (
            category,
            meaning
        )


        activity = (
            activities[
                key
            ]
        )


        activity[
            "flows"
        ].append(
            row[
                "flow_id"
            ]
        )


        if row[
            "process"
        ]:

            activity[
                "processes"
            ].add(
                row[
                    "process"
                ]
            )


        if row[
            "pid"
        ] is not None:

            activity[
                "pids"
            ].add(
                row[
                    "pid"
                ]
            )


        for hostname in names:

            activity[
                "hostnames"
            ].add(
                hostname
            )


        if row[
            "remote_ip"
        ]:

            activity[
                "remote_ips"
            ].add(
                row[
                    "remote_ip"
                ]
            )


        activity[
            "evidence"
        ].append(
            row[
                "evidence_confidence"
            ]
            or 0
        )


        activity[
            "classification"
        ].append(
            class_score
        )


    ordered = sorted(
        activities.items(),
        key=lambda item:
            len(
                item[1][
                    "flows"
                ]
            ),
        reverse=True
    )


    generated = utc_now()


    db_execute(
        """
        DELETE FROM activities
        WHERE session_id=?
        """,
        (
            SESSION_ID,
        )
    )


    for (
        category,
        meaning
    ), activity in ordered:


        evidence_average = (
            sum(
                activity[
                    "evidence"
                ]
            )
            /
            len(
                activity[
                    "evidence"
                ]
            )
        )


        classification_average = (
            sum(
                activity[
                    "classification"
                ]
            )
            /
            len(
                activity[
                    "classification"
                ]
            )
        )


        pids = sorted(
            activity[
                "pids"
            ]
        )


        representative_pid = (
            pids[0]
            if len(pids) == 1
            else None
        )


        db_execute(
            """
            INSERT INTO activities
            (
                session_id,
                generated_at,
                category,
                meaning,
                process,
                pid,
                flow_count,
                hostnames,
                remote_ips,
                evidence_confidence,
                classification_confidence,
                evidence_class
            )
            VALUES
            (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                SESSION_ID,
                generated,
                category,
                meaning,
                ", ".join(
                    sorted(
                        activity[
                            "processes"
                        ]
                    )
                ),
                representative_pid,
                len(
                    activity[
                        "flows"
                    ]
                ),
                " | ".join(
                    sorted(
                        activity[
                            "hostnames"
                        ]
                    )
                ),
                " | ".join(
                    sorted(
                        activity[
                            "remote_ips"
                        ]
                    )
                ),
                round(
                    evidence_average,
                    2
                ),
                round(
                    classification_average,
                    2
                ),
                "INFERRED"
            )
        )


    print()

    print(
        "=" * 72
    )

    print(
        " WHAT IS THIS COMPUTER DOING?"
    )

    print(
        "=" * 72
    )


    if not ordered:

        print(
            "No qualifying TCP activity observed."
        )

        print()

        return


    for (
        category,
        meaning
    ), activity in ordered:


        evidence_average = (
            sum(
                activity[
                    "evidence"
                ]
            )
            /
            len(
                activity[
                    "evidence"
                ]
            )
        )


        classification_average = (
            sum(
                activity[
                    "classification"
                ]
            )
            /
            len(
                activity[
                    "classification"
                ]
            )
        )


        print()

        print(
            f"[{category}]"
        )


        print(
            f"  Meaning : {meaning}"
        )


        print(
            "  Process : "
            +
            (
                ", ".join(
                    sorted(
                        activity[
                            "processes"
                        ]
                    )
                )
                or "[unknown]"
            )
        )


        print(
            f"  Flows   : "
            f"{len(activity['flows'])}"
        )


        print(
            f"  Evidence: "
            f"{evidence_average:.2f}"
        )


        print(
            f"  Inference: "
            f"{classification_average:.2f}"
        )


        if activity[
            "hostnames"
        ]:

            print(
                "  Hosts   : "
                +
                ", ".join(
                    sorted(
                        activity[
                            "hostnames"
                        ]
                    )[:8]
                )
            )


        if activity[
            "remote_ips"
        ]:

            print(
                "  IPs     : "
                +
                ", ".join(
                    sorted(
                        activity[
                            "remote_ips"
                        ]
                    )[:8]
                )
            )


    print()

    print(
        "OBSERVED   = process/socket evidence"
    )

    print(
        "CORRELATED = DNS-supported relationship"
    )

    print(
        "INFERRED   = activity interpretation"
    )

    print(
        "PROBED     = MachineObserver-generated traffic"
    )

    print(
        "UNKNOWN    = insufficient evidence"
    )

    print()


