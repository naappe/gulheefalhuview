ptr_cache = {}


def reverse_dns_worker(ip):

    if ip in ptr_cache:
        return

    try:

        name = socket.gethostbyaddr(
            ip
        )[0].rstrip(".")

    except Exception:

        name = None

    ptr_cache[
        ip
    ] = name


def get_ptr_without_blocking(ip):

    if ip in ptr_cache:

        return (
            ptr_cache[ip],
            ptr_cache[ip] is not None
        )


    # Critical:
    # Never block the 250 ms socket loop
    # waiting for DNS/PTR.
    threading.Thread(
        target=reverse_dns_worker,
        args=(ip,),
        daemon=True
    ).start()


    return (
        None,
        False
    )


