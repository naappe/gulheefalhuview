def get_process_info(pid):

    try:

        process = psutil.Process(pid)

        name = process.name()

        try:

            cmdline = " ".join(
                process.cmdline()
            )

        except Exception:

            cmdline = None

        return {
            "name": name,
            "cmdline": cmdline,
            "observed": True
        }

    except Exception:

        return {
            "name": "unknown",
            "cmdline": None,
            "observed": False
        }


