# ============================================================
# CREATE FLOW
# ============================================================

def create_flow(
    connection,
    baseline=False
):

    pid = connection.pid

    local_ip = (
        connection.laddr.ip
    )

    local_port = (
        connection.laddr.port
    )

    remote_ip = (
        connection.raddr.ip
    )

    remote_port = (
        connection.raddr.port
    )


    key = connection_key(
        connection
    )


    process = get_process_info(
        pid
    )


    names = sorted(
        dns_map.get(
            remote_ip,
            set()
        )
    )


    forward_dns = (
        len(names) > 0
    )


    reverse_name, reverse_ok = (
        get_ptr_without_blocking(
            remote_ip
        )
    )


    score = evidence_score(
        process[
            "observed"
        ],
        True,
        forward_dns
    )


    flow_id = str(
        uuid.uuid4()
    )


    timestamp = utc_now()


    status = (
        "BASELINE"
        if baseline
        else "OPEN"
    )


    cursor = db_execute(
        """
        INSERT INTO flows
        (
            flow_id,
            session_id,
            first_seen,
            last_seen,
            status,
            close_semantics,
            protocol,
            pid,
            process,
            cmdline,
            local_ip,
            local_port,
            remote_ip,
            remote_port,
            forward_names,
            reverse_name,
            process_observed,
            socket_observed,
            forward_dns_observed,
            reverse_dns_observed,
            evidence_confidence
        )
        VALUES
        (
            ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?,
            ?, ?, ?, ?, ?, ?, ?, ?, ?, ?
        )
        """,
        (
            flow_id,
            SESSION_ID,
            timestamp,
            timestamp,
            status,
            None,
            "TCP",
            pid,
            process[
                "name"
            ],
            process[
                "cmdline"
            ],
            local_ip,
            local_port,
            remote_ip,
            remote_port,
            (
                " | ".join(names)
                if names
                else None
            ),
            reverse_name,
            int(
                process[
                    "observed"
                ]
            ),
            1,
            int(
                forward_dns
            ),
            int(
                reverse_ok
            ),
            score
        )
    )


    active_flows[
        key
    ] = {

        "db_id":
            cursor.lastrowid,

        "flow_id":
            flow_id,

        "process":
            process[
                "name"
            ],

        "names":
            names,

        "baseline":
            baseline
    }


    if names:

        identity = (
            " | ".join(names)
        )

        source = (
            "FORWARD-DNS"
        )


    elif reverse_name:

        identity = reverse_name

        source = "PTR"


    else:

        identity = (
            "[unknown]"
        )

        source = "NONE"


    print(
        f"{status:<9} "
        f"{timestamp}  "
        f"{process['name']} "
        f"[{pid}]  "
        f"{identity}  "
        f"{local_ip}:{local_port} -> "
        f"{remote_ip}:{remote_port}  "
        f"dns={source} "
        f"evidence={score:.2f}"
    )


    # Don't generate probes for connections
    # that already existed when observer started.

    if not baseline:

        start_probes(
            remote_ip,
            remote_port,
            names
        )


