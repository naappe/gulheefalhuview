def db_execute(sql, params=()):

    with db_lock:

        cursor = db.execute(
            sql,
            params
        )

        db.commit()

        return cursor


def table_exists(name):

    row = db.execute(
        """
        SELECT 1
        FROM sqlite_master
        WHERE type='table'
          AND name=?
        """,
        (name,)
    ).fetchone()

    return row is not None


def table_columns(name):

    if not table_exists(name):
        return set()

    rows = db.execute(
        f'PRAGMA table_info("{name}")'
    ).fetchall()

    return {
        row[1]
        for row in rows
    }


def unique_legacy_name(base):

    candidate = base
    counter = 1

    while table_exists(candidate):

        candidate = (
            f"{base}_{counter}"
        )

        counter += 1

    return candidate


def preserve_if_incompatible(
    table,
    required_columns,
    legacy_base
):

    columns = table_columns(table)

    if not columns:
        return

    missing = (
        set(required_columns)
        - columns
    )

    if not missing:
        return

    destination = (
        unique_legacy_name(
            legacy_base
        )
    )

    print()
    print(
        f"MIGRATION: old '{table}' schema detected."
    )

    print(
        "Missing columns:",
        ", ".join(
            sorted(missing)
        )
    )

    print(
        f"Preserving it as '{destination}'."
    )

    db.execute(
        f'ALTER TABLE "{table}" '
        f'RENAME TO "{destination}"'
    )

    db.commit()


