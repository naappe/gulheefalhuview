# START ACTIVE PROBES
# ============================================================

def start_probes(
    ip,
    port,
    names
):

    if not ACTIVE_PROBES:
        return


    # Only use hostname when exactly one
    # forward-DNS candidate exists.

    hostname = None


    if len(names) == 1:

        hostname = names[0]


    threading.Thread(
        target=tls_probe,
        args=(
            ip,
            port,
            hostname
        ),
        daemon=True
    ).start()


    threading.Thread(
        target=http_probe,
        args=(
            ip,
            port,
            hostname
        ),
        daemon=True
    ).start()


