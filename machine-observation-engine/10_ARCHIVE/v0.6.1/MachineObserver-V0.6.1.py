# EVIDENCE SCORE
# ============================================================

def evidence_score(
    process_observed,
    socket_observed,
    forward_dns_observed
):

    score = 0.0

    if process_observed:
        score += 0.35

    if socket_observed:
        score += 0.40

    if forward_dns_observed:
        score += 0.25

    # PTR intentionally contributes nothing.

    return round(
        min(
            score,
            1.0
        ),
        2
    )


