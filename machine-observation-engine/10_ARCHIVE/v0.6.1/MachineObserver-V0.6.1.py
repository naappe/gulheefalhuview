def read_dns_cache():

    script = r"""
$ErrorActionPreference = 'SilentlyContinue'

Get-DnsClientCache |
Where-Object {
    $_.Entry -and $_.Data
} |
ForEach-Object {

    [PSCustomObject]@{

        Name = $_.Entry

        Data = $_.Data

        TTL = $_.TimeToLive
    }

} |
ConvertTo-Json -Compress
"""

    try:

        result = subprocess.run(
            [
                "powershell.exe",
                "-NoProfile",
                "-Command",
                script
            ],
            capture_output=True,
            text=True,
            timeout=5
        )

    except Exception:

        return []

    raw = result.stdout.strip()

    if not raw:
        return []

    try:

        records = json.loads(
            raw
        )

    except Exception:

        return []

    if isinstance(
        records,
        dict
    ):

        records = [
            records
        ]

    return records


def refresh_dns_cache():

    global dns_map
    global dns_snapshot

    records = read_dns_cache()

    current_map = defaultdict(
        set
    )

    current_snapshot = set()

    observed = utc_now()

    current_epoch = time.time()


    for record in records:

        hostname = str(
            record.get("Name")
            or ""
        ).strip().rstrip(".")


        address = str(
            record.get("Data")
            or ""
        ).strip()


        if not hostname:
            continue

        if not address:
            continue

        # Ignore CNAME values here.
        # They will become their own graph sensor later.
        if not is_ip(address):
            continue


        try:

            ttl = int(
                record.get("TTL")
                or 0
            )

        except Exception:

            ttl = 0


        current_map[
            address
        ].add(
            hostname
        )


        evidence_key = (
            hostname.lower(),
            address
        )


        current_snapshot.add(
            evidence_key
        )


        # Only insert when a hostname/IP pair
        # appears for the first time in the
        # current in-memory observation state.
        if evidence_key not in dns_snapshot:

            db_execute(
                """
                INSERT INTO dns_evidence
                (
                    session_id,
                    observed_at,
                    hostname,
                    address,
                    ttl,
                    expires_at,
                    source
                )
                VALUES
                (?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    SESSION_ID,
                    observed,
                    hostname,
                    address,
                    ttl,
                    current_epoch + ttl,
                    "WINDOWS_DNS_CACHE"
                )
            )


    dns_snapshot = (
        current_snapshot
    )

    dns_map = {
        ip: set(names)
        for ip, names
        in current_map.items()
    }


