"""
Machine Observer V0.6.1

Evidence architecture:

REAL SYSTEM
    |
    +-- Process / PID / Command line
    +-- TCP socket observations
    +-- Windows DNS cache
    +-- PTR contextual enrichment
    |
    +-- Optional active TLS/HTTP probes
    |
    v
SQLite Evidence Store
    |
    v
Activity Correlator
    |
    v
"What is this computer doing?"

Evidence classes:

OBSERVED
    Direct local evidence.

CORRELATED
    Association supported by other evidence, such as DNS.

INFERRED
    Interpretation generated from observed/correlated evidence.

PROBED
    A new connection deliberately generated by MachineObserver.

UNKNOWN
    Evidence is insufficient.

IMPORTANT:
- HTTPS payloads are NOT decrypted.
- PTR is NOT treated as proof of the hostname used by an application.
- TLS/HTTP probes are stored separately from observed application traffic.
- Initial sockets are BASELINE, not falsely labelled OPEN.
- A socket disappearing from a polling snapshot is DISAPPEARED,
  not claimed to be an exact TCP FIN/RST event.
"""

