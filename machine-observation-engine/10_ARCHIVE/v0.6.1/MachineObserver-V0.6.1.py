# HTTP ACTIVE PROBE
# ============================================================

def http_probe(
    ip,
    port,
    hostname
):

    if not ACTIVE_PROBES:
        return

    if not HTTP_PROBE_ENABLED:
        return

    if port not in (
        80,
        443
    ):
        return

    if not safe_for_active_probe(
        ip
    ):
        return


    key = (
        ip,
        port,
        hostname
    )


    with probe_lock:

        if key in http_probed:
            return

        if (
            len(http_probed)
            >= MAX_HTTP_PROBES
        ):
            return

        http_probed.add(
            key
        )


    host = (
        hostname
        if hostname
        else ip
    )


    try:

        if port == 443:

            context = (
                ssl.create_default_context()
            )

            connection = (
                http.client.HTTPSConnection(
                    ip,
                    port,
                    timeout=PROBE_TIMEOUT,
                    context=context
                )
            )

        else:

            connection = (
                http.client.HTTPConnection(
                    ip,
                    port,
                    timeout=PROBE_TIMEOUT
                )
            )


        connection.request(
            "HEAD",
            "/",
            headers={
                "Host": host,
                "User-Agent":
                    "MachineObserver/0.6.1"
            }
        )


        response = (
            connection.getresponse()
        )


        result = {

            "status":
                response.status,

            "reason":
                response.reason,

            "headers":
                dict(
                    response.getheaders()
                )
        }


        db_execute(
            """
            INSERT INTO probes
            (
                session_id,
                observed_at,
                probe_type,
                remote_ip,
                remote_port,
                hostname_candidate,
                result,
                source
            )
            VALUES
            (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                SESSION_ID,
                utc_now(),
                "HTTP_HEAD",
                ip,
                port,
                hostname,
                json.dumps(
                    result,
                    default=str
                ),
                "ACTIVE_PROBE"
            )
        )


        print(
            "PROBE HTTP  "
            f"{host} "
            f"{ip}:{port} "
            f"status={response.status}"
        )


        connection.close()


    except Exception:

        pass


