def scan_tcp():

    current = set()


    try:

        connections = (
            psutil.net_connections(
                kind="tcp"
            )
        )

    except Exception as error:

        print(
            "TCP sensor error:",
            error
        )

        return


    for connection in connections:

        if (
            connection.status
            != psutil.CONN_ESTABLISHED
        ):
            continue


        if not connection.raddr:
            continue


        if connection.pid is None:
            continue


        key = connection_key(
            connection
        )


        current.add(
            key
        )


        if key not in active_flows:

            create_flow(
                connection,
                baseline=False
            )


        else:

            information = (
                active_flows[
                    key
                ]
            )


            # Update PTR later if the
            # background resolver completed.

            remote_ip = key[4]

            ptr = ptr_cache.get(
                remote_ip
            )


            if ptr:

                db_execute(
                    """
                    UPDATE flows

                    SET
                        last_seen=?,
                        reverse_name=?,
                        reverse_dns_observed=1

                    WHERE id=?
                    """,
                    (
                        utc_now(),
                        ptr,
                        information[
                            "db_id"
                        ]
                    )
                )

            else:

                db_execute(
                    """
                    UPDATE flows

                    SET last_seen=?

                    WHERE id=?
                    """,
                    (
                        utc_now(),
                        information[
                            "db_id"
                        ]
                    )
                )


    disappeared = []


    for key, information in list(
        active_flows.items()
    ):

        if key in current:
            continue


        timestamp = utc_now()


        db_execute(
            """
            UPDATE flows

            SET
                last_seen=?,
                status='DISAPPEARED',
                close_semantics=
                    'SNAPSHOT_DISAPPEARANCE'

            WHERE id=?
            """,
            (
                timestamp,
                information[
                    "db_id"
                ]
            )
        )


        (
            protocol,
            pid,
            local_ip,
            local_port,
            remote_ip,
            remote_port
        ) = key


        print(
            "DISAPPEAR "
            f"{timestamp}  "
            f"{information['process']} "
            f"[{pid}]  "
            f"{local_ip}:{local_port} -> "
            f"{remote_ip}:{remote_port}"
        )


        disappeared.append(
            key
        )


    for key in disappeared:

        active_flows.pop(
            key,
            None
        )


