ptr_cache = {}


def reverse_dns_worker(ip):

    if ip in ptr_cache:
        return

    try:

        name = socket.gethostbyaddr(
            ip
        )[0].rstrip(".")

    except Exception:

        name = None

    ptr_cache[
        ip
    ] = name


def get_ptr_without_blocking(ip):

    if ip in ptr_cache:

        return (
            ptr_cache[ip],
            ptr_cache[ip] is not None
        )


    # Critical:
    # Never block the 250 ms socket loop
    # waiting for DNS/PTR.
    threading.Thread(
        target=reverse_dns_worker,
        args=(ip,),
        daemon=True
    ).start()


    return (
        None,
        False
    )


# ============================================================
# EVIDENCE SCORE
# ============================================================

def evidence_score(
    process_observed,
    socket_observed,
    forward_dns_observed
):

    score = 0.0

    if process_observed:
        score += 0.35

    if socket_observed:
        score += 0.40

    if forward_dns_observed:
        score += 0.25

    # PTR intentionally contributes nothing.

    return round(
        min(
            score,
            1.0
        ),
        2
    )


