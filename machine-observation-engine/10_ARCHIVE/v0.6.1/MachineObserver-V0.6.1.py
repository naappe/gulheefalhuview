def is_ip(value):

    try:

        ipaddress.ip_address(
            value
        )

        return True

    except Exception:

        return False


def safe_for_active_probe(ip):

    try:

        address = (
            ipaddress.ip_address(ip)
        )

    except Exception:

        return False

    if address.is_loopback:
        return False

    if address.is_link_local:
        return False

    if address.is_multicast:
        return False

    if address.is_unspecified:
        return False

    if address.is_private:
        return False

    return True


